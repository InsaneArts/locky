--- The glyph for one character (letters are matched in upper case), or the blank glyph.
function M.glyph(char)
  return glyphs[char] or glyphs[char:upper()] or glyphs[" "]
end

--- True when the dot at row r, column c (both from 1) of a glyph is lit.
function M.lit(glyph, r, c)
  return glyph[r]:byte(c) == 35 -- "#"
end

